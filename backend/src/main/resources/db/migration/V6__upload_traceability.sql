    ADD COLUMN IF NOT EXISTS uploaded_by BIGINT;

ALTER TABLE lesson_resources
    ADD COLUMN IF NOT EXISTS extraction_status VARCHAR(30);

CREATE TABLE IF NOT EXISTS lesson_resource_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_resource_id BIGINT,
    lesson_id BIGINT NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    file_name VARCHAR(255),
    content_type VARCHAR(100),
    size_bytes BIGINT,
    storage_key VARCHAR(255),
    extracted_text TEXT,
    extraction_status VARCHAR(30),
    uploaded_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);