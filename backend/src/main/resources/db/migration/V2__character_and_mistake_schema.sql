ALTER TABLE student_mistakes
    ADD COLUMN IF NOT EXISTS source VARCHAR(20) NOT NULL DEFAULT 'PLACEMENT';

CREATE TABLE IF NOT EXISTS character_episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    episode_json TEXT NOT NULL,
    finished BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_character_episode_lesson
        FOREIGN KEY (lesson_id) REFERENCES lessons(id),
    CONSTRAINT fk_character_episode_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS character_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    text TEXT NOT NULL,
    correction_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_character_message_episode
        FOREIGN KEY (episode_id) REFERENCES character_episodes(id)
);

CREATE INDEX IF NOT EXISTS ix_character_episode_student_lesson
    ON character_episodes (user_id, lesson_id, created_at);

CREATE INDEX IF NOT EXISTS ix_character_message_episode_created
    ON character_messages (episode_id, created_at);
